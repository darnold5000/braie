const iconMap: Record<SocialLink["icon"], React.ComponentType<{ className?: string }>> = {
  instagram: InstagramIcon,
  tiktok: TikTokIcon,
  youtube: YouTubeIcon,
  facebook: FacebookIcon,
  pinterest: PinterestIcon,
  email: Mail,
  linkedin: LinkedInIcon,
};

type SocialLinksProps = {
  links?: SocialLink[];
  className?: string;
  iconClassName?: string;
};

export function SocialLinks({
  links,
  className,
  iconClassName = "h-5 w-5",
}: SocialLinksProps) {
  const items = links ?? [];

  return (
    <div className={cn("flex flex-wrap gap-3", className)}>
      {items.map((link) => {
        const Icon = iconMap[link.icon];
        return (
          <a
            key={link.platform}
            href={link.href}
            target={link.icon === "email" ? undefined : "_blank"}
            rel={link.icon === "email" ? undefined : "noopener noreferrer"}
            aria-label={link.label}
            className="flex h-10 w-10 items-center justify-center rounded-full bg-background text-muted-foreground shadow-sm ring-1 ring-border transition-all hover:bg-primary hover:text-primary-foreground hover:ring-primary"
          >
            <Icon className={iconClassName} />
          </a>
        );
      })}
    </div>
  );
}

export { InstagramIcon, TikTokIcon, YouTubeIcon };
